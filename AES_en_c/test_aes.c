// --- Helper pour les tests ---
int compare_state(state s1, state s2) {
    for (int i = 0; i < 4; i++) {
        for (int j = 0; j < 4; j++) {
            if (s1[i][j] != s2[i][j]) return 0;
        }
    }
    return 1;
}

